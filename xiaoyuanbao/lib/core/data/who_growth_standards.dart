  /// 根据月龄和性别获取体重标准值
  static Map<String, double> getWeightStandard(int ageMonths, {bool isMale = true}) {
    final data = isMale ? weightBoys : weightGirls;
    return _getInterpolatedValues(data, ageMonths);
  }

  /// 根据月龄和性别获取身高标准值
  static Map<String, double> getHeightStandard(int ageMonths, {bool isMale = true}) {
    final data = isMale ? heightBoys : heightGirls;
    return _getInterpolatedValues(data, ageMonths);
  }

  /// 根据月龄和性别获取头围标准值
  static Map<String, double> getHeadCircumferenceStandard(int ageMonths, {bool isMale = true}) {
    final data = isMale ? headBoys : headGirls;
    // 头围数据只到60个月，之后使用最后的数据
    if (ageMonths > 60) {
      return data[60]!;
    }
    return _getInterpolatedValues(data, ageMonths);
  }

  /// 计算百分位
  static double calculatePercentile(double value, Map<String, double> standard) {
    final p3 = standard['p3']!;
    final p50 = standard['p50']!;
    final p97 = standard['p97']!;

    if (value <= p3) return 3;
    if (value >= p97) return 97;

    // 简化计算：线性插值
    if (value < p50) {
      return 3 + (value - p3) / (p50 - p3) * 47;
    } else {
      return 50 + (value - p50) / (p97 - p50) * 47;
    }
  }

  /// 插值获取标准值
  static Map<String, double> _getInterpolatedValues(
    Map<int, Map<String, double>> data,
    int ageMonths,
  ) {
    if (data.containsKey(ageMonths)) {
      return data[ageMonths]!;
    }

    // 找到最接近的两个月龄进行插值
    final keys = data.keys.toList()..sort();
    int lowerKey = keys.first;
    int upperKey = keys.last;

    for (final key in keys) {
      if (key < ageMonths) {
        lowerKey = key;
      } else {
        upperKey = key;
        break;
      }
    }

    if (lowerKey == upperKey) {
      return data[lowerKey]!;
    }

    final lower = data[lowerKey]!;
    final upper = data[upperKey]!;
    final ratio = (ageMonths - lowerKey) / (upperKey - lowerKey);

    return {
      'p3': lower['p3']! + (upper['p3']! - lower['p3']!) * ratio,
      'p50': lower['p50']! + (upper['p50']! - lower['p50']!) * ratio,
      'p97': lower['p97']! + (upper['p97']! - lower['p97']!) * ratio,
    };
  }
